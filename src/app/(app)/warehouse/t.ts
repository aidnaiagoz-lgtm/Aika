/** Қойма қатесін таңдалған тілге аудару (орысша аудармасы жоқ болса — қазақша қалады). */
export function localizeError(msg: string, locale: Locale): string {
  if (locale !== "ru") return msg;
  if (RU_ERRORS[msg]) return RU_ERRORS[msg];
  for (const [re, f] of RU_ERROR_PATTERNS) {
    const m = msg.match(re);
    if (m) return f(m);
  }
  return msg;
}
